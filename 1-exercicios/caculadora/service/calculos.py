import math

class Calculos:
    
    def adicao(numA, numB):
        return numA + numB
    
    def subtracao(numA, numB):
        return numA + numB
    
    def multiplicacao(numA, numB):
        return numA * numB
    
    def dicisao(numA, numB):
        return numA / numB
    
    def raizQuadrada(numA):
        return math.sqrt(numA) 