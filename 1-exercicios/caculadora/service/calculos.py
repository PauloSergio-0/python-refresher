import math

class Calculos:
    
    def adicao(numA, numB):
        return print(f"{numA + numB}")
    
    def subtracao(numA, numB):
        return print(f"{numA - numB}")
    
    def multiplicacao(numA, numB):
        return print(f"{numA * numB}")
    
    def divisao(numA, numB):
        return print(f"{numA / numB}")
    
    def raizQuadrada(numA):
        return print(f"{math.sqrt(numA)}")